function toggleDropdown() {
  const dropdown = document.getElementById("languageDropdown");

  if (!dropdown) {
    return;
  }

  dropdown.style.display = dropdown.style.display === "flex" ? "none" : "flex";
}

function getCookieLanguage() {
  const match = document.cookie.match(
    new RegExp("(^| )selectedLanguage=([^;]+)"),
  );
  return match ? decodeURIComponent(match[2]) : null;
}

function getActiveLanguageFromPanel() {
  const activeItem = document.querySelector(
    ".locale-menu li.active[data-lang]",
  );

  if (activeItem && ["es", "en", "pt"].includes(activeItem.dataset.lang)) {
    return activeItem.dataset.lang;
  }

  const panelFlag = document.querySelector(".am-lang-anchor img");

  if (panelFlag && ["es", "en", "pt"].includes(panelFlag.getAttribute("alt"))) {
    return panelFlag.getAttribute("alt");
  }

  return null;
}

function getCurrentLanguage() {
  let lang =
    getActiveLanguageFromPanel() ||
    localStorage.getItem("selectedLanguage") ||
    getCookieLanguage() ||
    "es";

  if (!["es", "en", "pt"].includes(lang)) {
    lang = "es";
  }

  localStorage.setItem("selectedLanguage", lang);
  document.cookie = `selectedLanguage=${lang}; path=/; max-age=31536000; SameSite=Lax`;

  return lang;
}

function selectLanguage(lang, closeDropdown = true) {
  localStorage.setItem("selectedLanguage", lang);
  document.cookie = `selectedLanguage=${lang}; path=/; max-age=31536000; SameSite=Lax`;

  const selectedOption = document.querySelector(
    ".language-select .selected-option span",
  );
  const selectedImg = document.querySelector(
    ".language-select .selected-option img",
  );

  const languages = {
    es: {
      text: "Español",
      flag: "https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/1f1ea-1f1f8.svg",
    },
    en: {
      text: "English",
      flag: "https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/1f1ec-1f1e7.svg",
    },
    pt: {
      text: "Português",
      flag: "https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/1f1f5-1f1f9.svg",
    },
  };

  if (selectedOption) selectedOption.textContent = languages[lang].text;
  if (selectedImg) selectedImg.src = languages[lang].flag;

  // Traducir todos los elementos con data-translate
  document.querySelectorAll("[data-translate]").forEach((el) => {
    const key = el.getAttribute("data-translate");
    const currentTranslations = translations[lang] || translations.es;

    if (currentTranslations && currentTranslations[key]) {
      el.innerHTML = currentTranslations[key];
    }
  });

  document.querySelectorAll("[data-translate-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-translate-placeholder");
    const currentTranslations = translations[lang] || translations.es;

    if (currentTranslations && currentTranslations[key]) {
      el.setAttribute("placeholder", currentTranslations[key]);
    }
  });

  document.querySelectorAll("[data-translate-aria-label]").forEach((el) => {
    const key = el.getAttribute("data-translate-aria-label");
    const currentTranslations = translations[lang] || translations.es;

    if (currentTranslations && currentTranslations[key]) {
      el.setAttribute("aria-label", currentTranslations[key]);
    }
  });

  document.querySelectorAll("[data-translate-title]").forEach((el) => {
    const key = el.getAttribute("data-translate-title");
    const currentTranslations = translations[lang] || translations.es;

    if (currentTranslations && currentTranslations[key]) {
      el.setAttribute("title", currentTranslations[key]);
    }
  });

  document.dispatchEvent(
    new CustomEvent("languageChanged", {
      detail: { lang: lang },
    }),
  );

  if (closeDropdown) toggleDropdown();
}

